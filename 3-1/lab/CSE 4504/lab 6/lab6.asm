INIT MACRO SIZE
    MOV CL, SIZE
    MOV SI, 0
ENDM

SEARCH MACRO ARR, DIGIT, FOUND_MSG, NOTFOUND_MSG
    SEARCH_LOOP:
        MOV AL, ARR[SI]
        CMP AL, DIGIT
        JE FOUND
        INC SI
        LOOP SEARCH_LOOP 
    MOV DX, OFFSET NOTFOUND_MSG
    CALL DSPLY_STRING
    JMP END_MACRO
    
    FOUND:
        MOV DX, OFFSET FOUND_MSG
        CALL DSPLY_STRING
        
    END_MACRO:
        ENDM


ORG 0100H  

.DATA
ARR DB 1, 6, 2, 9, 5
ARRSIZE DB 6d
STARTMSG DB 0DH, 0AH, 'Input a number', 0DH, 0AH, '$'
FOUND_MSG DB 0DH, 0AH, 'Digit found!', 0DH, 0AH, '$'
NOTFOUND_MSG DB 0DH, 0AH, 'Digit not found :(', 0DH, 0AH, '$'

.CODE
MAIN PROC
MOV AX, @DATA
MOV DS, AX   

INIT ARRSIZE

MOV DX, OFFSET STARTMSG
CALL DSPLY_STRING

CALL INPUT

SEARCH ARR, BL, FOUND_MSG, NOTFOUND_MSG

MOV AH, 4CH
INT 21H
MAIN ENDP

INPUT PROC
    MOV AH, 01H
    INT 21H
    SUB AL, '0'
    MOV BL, AL
    RET
INPUT ENDP

DSPLY_STRING PROC ; Declaration of PROCEDURE
    MOV AH, 09H
    INT 21H
    RET
DSPLY_STRING ENDP  

END MAIN

